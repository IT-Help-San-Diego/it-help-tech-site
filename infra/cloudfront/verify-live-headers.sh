#!/usr/bin/env bash
# Verify live response headers for the corporate site edge.
# This is intentionally separate from the viewer-request function tests: HSTS/CSP
# are response-header-policy concerns, not viewer-request redirect logic.
set -euo pipefail

check_headers() {
  local url="$1"
  local expected_status_pattern="${2:-^HTTP/[0-9.]+ 200}"
  local expected_location="${3:-}"

  local headers
  headers=$(curl -sS -I "$url" | tr -d '\r')
  printf '%s\n' "--- $url"
  printf '%s\n' "$headers" | awk 'BEGIN{IGNORECASE=1} /^HTTP\// || /^location:/ || /^cache-control:/ || /^strict-transport-security:/ || /^content-security-policy:/ || /^x-frame-options:/ || /^x-content-type-options:/ {print}'

  printf '%s\n' "$headers" | grep -qiE "$expected_status_pattern"
  if [[ -n "$expected_location" ]]; then
    printf '%s\n' "$headers" | grep -Fqi "location: $expected_location"
    printf '%s\n' "$headers" | grep -Fqi 'cache-control: public,max-age=300'
  fi

  printf '%s\n' "$headers" | grep -qi '^strict-transport-security: max-age=63072000; includeSubDomains; preload$'
  printf '%s\n' "$headers" | grep -qi '^x-frame-options: DENY$'
  printf '%s\n' "$headers" | grep -qi '^x-content-type-options: nosniff$'
  printf '%s\n' "$headers" | grep -qi '^content-security-policy: .*frame-ancestors '\''none'\'''
  printf '%s\n' "$headers" | grep -qi '^content-security-policy: .*upgrade-insecure-requests'
}

check_headers "https://www.it-help.tech/"
check_headers "https://www.it-help.tech/services/"
check_headers "https://www.it-help.tech/corrections/"
check_headers "https://www.it-help.tech/llms-full.txt"

# Existing viewer-request function redirects. These are the best regression
# canaries for PR #707 because they are generated by the same CloudFront
# Function the withdrawal redirects will extend.
check_headers "https://it-help.tech/" '^HTTP/[0-9.]+ 301' 'https://www.it-help.tech/'
check_headers "https://www.it-help.tech/blog/tag/dns/" '^HTTP/[0-9.]+ 301' '/blog/#dns'
check_headers "https://www.it-help.tech/blog/category/Mac+Tips" '^HTTP/[0-9.]+ 301' '/blog/#mac-tips'

printf 'live edge response-header and redirect-header checks passed\n'
